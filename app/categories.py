"""Единый справочник категорий сюжетов.

Отсюда берутся список категорий и их описания для промпта (pipeline.py),
приём сюжетов в ленту и русские названия для клиента (/api/v1/meta).
Новая категория добавляется одной строкой здесь — приложение получит
её название с сервера без пересборки.
"""

# slug: (название для пользователя, описание для LLM)
CATEGORIES: dict[str, tuple[str, str]] = {
    'politics': ('Политика', 'политика, выборы, войны, дипломатия'),
    'finance': ('Финансы', 'экономика, рынки, компании'),
    'science_tech': ('Наука и техника', 'наука, технологии, медицина'),
    'sport': ('Спорт', 'спорт'),
    'culture': ('Культура', 'кино, музыка, искусство, литература'),
    'incidents': ('Происшествия',
                  'катастрофы, аварии, преступления, стихийные бедствия'),
    'celebrity': ('Светская хроника', 'светская хроника, личная жизнь знаменитостей'),
    # other — не принимается в ленту (погода, разные события в одной группе)
    'other': ('Другое', 'всё остальное'),
}

REJECTED_CATEGORY = 'other'

# Категории, сюжеты которых принимаются в ленту.
ACCEPTED_CATEGORIES = tuple(c for c in CATEGORIES if c != REJECTED_CATEGORY)

# slug -> русское название, отдаётся клиенту.
TITLES = {slug: title for slug, (title, _) in CATEGORIES.items()}


def prompt_description() -> str:
    """Строки для промпта: «slug — описание» по каждой категории."""
    return '\n'.join(f'{slug} — {desc}' for slug, (_, desc) in CATEGORIES.items())
